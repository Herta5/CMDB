-- 本文件在 PostgreSQL 管理员连接下创建 CMDB 全部业务结构；应用账号仅在授权范围内执行 CRUD。
\set ON_ERROR_STOP on

-- Docker 初始化约束与本保护同时确保业务表和序列由 postgres 管理员拥有。
DO $$
BEGIN
    IF current_user <> 'postgres' THEN
        RAISE EXCEPTION 'CMDB 初始化结构必须由 postgres 管理员执行';
    END IF;
END
$$;

BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL CHECK (username ~ '^[A-Za-z0-9_]{1,64}$'),
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    email VARCHAR(255),
    global_role VARCHAR(32) NOT NULL DEFAULT 'user' CHECK (global_role IN ('system_admin', 'user')),
    status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    last_login_at TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
    owner_user_id BIGINT,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_projects_code UNIQUE (code),
    CONSTRAINT fk_projects_owner_user_id FOREIGN KEY (owner_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_projects_owner_user_id ON projects (owner_user_id);

CREATE TABLE project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('project_admin', 'member')),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_project_members_project_user UNIQUE (project_id, user_id),
    CONSTRAINT fk_project_members_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_project_members_user_id ON project_members (user_id);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT,
    project_id BIGINT,
    action VARCHAR(128) NOT NULL,
    resource_type VARCHAR(64) NOT NULL,
    resource_id VARCHAR(255),
    detail JSONB,
    request_ip VARCHAR(45),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE INDEX idx_audit_logs_project_created_at ON audit_logs (project_id, created_at);
CREATE INDEX idx_audit_logs_actor_created_at ON audit_logs (actor_id, created_at);
CREATE INDEX idx_audit_logs_resource ON audit_logs (resource_type, resource_id);

CREATE TABLE resource_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    provider VARCHAR(32) NOT NULL CHECK (provider IN ('aliyun', 'aws')),
    name VARCHAR(128) NOT NULL,
    region VARCHAR(128) NOT NULL DEFAULT '',
    encrypted_credential TEXT NOT NULL,
    credential_hint VARCHAR(128) NOT NULL DEFAULT '',
    config JSONB,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sync_interval_minutes INTEGER NOT NULL DEFAULT 60 CHECK (sync_interval_minutes > 0),
    last_sync_at TIMESTAMPTZ(3),
    next_sync_at TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_resource_sources_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE
);

CREATE INDEX idx_resource_sources_project_provider ON resource_sources (project_id, provider);

CREATE TABLE resources_servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    provider VARCHAR(32) NOT NULL CHECK (provider IN ('aliyun', 'aws')),
    resource_type VARCHAR(64) NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL DEFAULT '',
    region VARCHAR(128) NOT NULL DEFAULT '',
    zone VARCHAR(128) NOT NULL DEFAULT '',
    cloud_status VARCHAR(64) NOT NULL DEFAULT '',
    asset_status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (asset_status IN ('active', 'lost')),
    private_ips JSONB,
    public_ips JSONB,
    raw_attributes JSONB,
    first_seen_at TIMESTAMPTZ(3) NOT NULL,
    last_seen_at TIMESTAMPTZ(3) NOT NULL,
    missing_since TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_resources_servers_identity UNIQUE (source_id, resource_type, external_id),
    CONSTRAINT fk_resources_servers_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_servers_source FOREIGN KEY (source_id) REFERENCES resource_sources (id) ON DELETE CASCADE
);

CREATE INDEX idx_resources_servers_project_provider ON resources_servers (project_id, provider);
CREATE INDEX idx_resources_servers_status ON resources_servers (asset_status);

CREATE TABLE resources_databases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
