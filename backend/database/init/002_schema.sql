    engine VARCHAR(64) NOT NULL DEFAULT '',
    engine_version VARCHAR(64) NOT NULL DEFAULT '',
    endpoints JSONB,
    raw_attributes JSONB,
    first_seen_at TIMESTAMPTZ(3) NOT NULL,
    last_seen_at TIMESTAMPTZ(3) NOT NULL,
    missing_since TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_resources_databases_identity UNIQUE (source_id, resource_type, external_id),
    CONSTRAINT fk_resources_databases_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_databases_source FOREIGN KEY (source_id) REFERENCES resource_sources (id) ON DELETE CASCADE
);

CREATE INDEX idx_resources_databases_project_provider ON resources_databases (project_id, provider);
CREATE INDEX idx_resources_databases_status ON resources_databases (asset_status);

CREATE TABLE resources_load_balancers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    provider VARCHAR(32) NOT NULL CHECK (provider IN ('aliyun', 'aws')),
    resource_type VARCHAR(64) NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL DEFAULT '',
    region VARCHAR(128) NOT NULL DEFAULT '',
    zone VARCHAR(128) NOT NULL DEFAULT '',
    cloud_status VARCHAR(64) NOT NULL DEFAULT '',
    asset_status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (asset_status IN ('active', 'lost')),
    network_type VARCHAR(32) NOT NULL DEFAULT '',
    endpoints JSONB,
    raw_attributes JSONB,
    first_seen_at TIMESTAMPTZ(3) NOT NULL,
    last_seen_at TIMESTAMPTZ(3) NOT NULL,
    missing_since TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_resources_load_balancers_identity UNIQUE (source_id, resource_type, external_id),
    CONSTRAINT fk_resources_load_balancers_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_resources_load_balancers_source FOREIGN KEY (source_id) REFERENCES resource_sources (id) ON DELETE CASCADE
);

CREATE INDEX idx_resources_load_balancers_project_provider ON resources_load_balancers (project_id, provider);
CREATE INDEX idx_resources_load_balancers_status ON resources_load_balancers (asset_status);

CREATE TABLE sync_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    previous_job_id BIGINT,
    status VARCHAR(32) NOT NULL CHECK (status IN ('queued', 'running', 'success', 'partial_success', 'failed')),
    trigger VARCHAR(32) NOT NULL CHECK (trigger IN ('manual', 'scheduled')),
    statistics JSONB,
    error_summary VARCHAR(500) NOT NULL DEFAULT '',
    started_at TIMESTAMPTZ(3) NOT NULL,
    finished_at TIMESTAMPTZ(3),
    CONSTRAINT fk_sync_jobs_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_sync_jobs_source FOREIGN KEY (source_id) REFERENCES resource_sources (id) ON DELETE CASCADE,
    CONSTRAINT fk_sync_jobs_previous FOREIGN KEY (previous_job_id) REFERENCES sync_jobs (id) ON DELETE SET NULL
);

CREATE INDEX idx_sync_jobs_source_started ON sync_jobs (source_id, started_at);
CREATE INDEX idx_sync_jobs_project_started ON sync_jobs (project_id, started_at);
CREATE INDEX idx_sync_jobs_previous ON sync_jobs (previous_job_id);
CREATE UNIQUE INDEX uk_sync_jobs_source_running ON sync_jobs (source_id) WHERE status = 'running';

