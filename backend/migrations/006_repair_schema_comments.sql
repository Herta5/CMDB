-- CMDB 元数据修复迁移：统一使用 utf8mb4 重写全部表和字段注释，不修改业务数据。
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;

ALTER TABLE `users`
  MODIFY COLUMN `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '全局用户唯一标识',
  MODIFY COLUMN `username` VARCHAR(64) NOT NULL COMMENT '登录用户名，全局唯一',
  MODIFY COLUMN `password_hash` VARCHAR(255) NOT NULL COMMENT 'bcrypt 密码哈希，禁止保存明文',
  MODIFY COLUMN `display_name` VARCHAR(128) NOT NULL COMMENT '页面展示的用户名称',
  MODIFY COLUMN `email` VARCHAR(255) NULL COMMENT '用户联系邮箱',
  MODIFY COLUMN `global_role` ENUM('system_admin','user') NOT NULL DEFAULT 'user' COMMENT '全局角色：系统管理员或普通用户',
  MODIFY COLUMN `status` ENUM('active','disabled') NOT NULL DEFAULT 'active' COMMENT '用户启用状态',
  MODIFY COLUMN `last_login_at` DATETIME(3) NULL COMMENT '最近一次成功登录时间',
  MODIFY COLUMN `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  MODIFY COLUMN `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后更新时间',
  COMMENT = 'CMDB 全局用户身份表';

